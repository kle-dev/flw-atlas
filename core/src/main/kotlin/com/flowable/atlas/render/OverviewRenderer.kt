/**
 * The Markdown OVERVIEW report — every model, relationship and the access map.
 *
 * `result` is the raw (un-normalized) map produced by [com.flowable.atlas.graph.Atlas.extract]; its
 * values are JSON-shaped (Map / List / String / Number / Boolean / null). Numbers print without a
 * trailing `.0` ([numStr]); the result is returned WITHOUT a trailing newline (the caller adds it).
 *
 * Originally a byte-exact port of `flowable_atlas.py`, which is why [pyStr] exists. Scalars still go
 * through it; **lists, maps and optional values must go through [Fmt] instead** — via `pyStr` they
 * printed as `['a', 'b']` / `{'k': 'v'}` / `None`, which is Python's debugging output, not a report.
 * `MarkdownHygieneTest` fails if any of those reach the page.
 */
object OverviewRenderer {

    /** Interfaces that mark a class as Flowable "glue" code. */
    private val GLUE_INTERFACES = setOf(
        "JavaDelegate", "ExecutionListener", "TaskListener", "ActivityBehavior",
        "PlanItemJavaDelegate", "PlanItemActivityBehavior", "CaseInstanceLifecycleListener",
        "PlanItemInstanceLifecycleListener", "DelegatePlanItemActivityBehavior",
        "AbstractServiceTask", "JavaDelegatePlanItem", "FlowableEventListener",
    )

    // model type → normalized graph/index node type (bpmn→process, cmmn→case, …).
    private val NORMALIZE_TYPE = com.flowable.atlas.parsing.ModelKinds.NORMALIZE_TYPE

    /**
     * Findings listed per check before eliding the rest. A project with 400 script-inferred variables
     * should not push its two broken expressions off the page — and the full list is in `graph.json`.
     */
    private const val FINDINGS_PER_CHECK = 20

    /** Node types that already have a section of their own, so the "also in the graph" line skips them. */
    private val REPORTED_NODE_TYPES = setOf(
        "app", "process", "case", "decision", "form", "page", "dataObject", "dataDictionary",
        "service", "agent", "channel", "event", "action", "securityPolicy", "liquibase",
        "java", "endpoint", "group", "variable", "expression", "binding", "external",
    )

    /**
     * Caps for the sections that grow linearly with the project. On a real 359-model app the report was
     * 373 KB / 4019 lines — past the point where anyone, human or model, reads it — because these lists
     * were unbounded. Each cap ends in a pointer to the graph, which holds the full set.
     */
    private const val FORM_FIELDS_LISTED = 40
    private const val RESOLVED_REFS_LISTED = 120

    /** Rule rows listed per decision table before eliding — enough to see the shape of the logic. */
    private const val DMN_RULES_LISTED = 12

    /** Column rows listed per service in the data-layer chain (only the problem rows are listed). */
    private const val SCHEMA_ROWS_LISTED = 12

    /** A parameter is either a plain name or `{name, type, …}` depending on the model. */
    private fun paramName(v: Any?): String = when (v) {
        is Map<*, *> -> (v["name"] ?: v["key"] ?: "").toString()
        else -> v?.toString() ?: ""
    }

    /** Caps for §13. A 381-variable project must not turn the report into a variable dictionary. */
    private const val VARIABLES_LISTED = 60
    private const val EXPRESSION_GROUPS = 40
    private const val EXPRESSIONS_PER_GROUP = 8

    /**
     * @param siblings what is written beside the report. The pointers to the graph and the diagrams name
     *   those files only when they are there; a single-file run used to advertise both.
     */
    fun render(result: Map<String, Any?>, root: File, siblings: Siblings = Siblings.ALL): String {
        val L = ArrayList<String>()
        fun hdr(n: Int, title: String) = L.add("## $n. $title\n")

        val s = asMap(result["stats"])
        val projName = Fmt.projectName(root)
        L.add("# Flowable App Overview — `$projName`\n")
        val an = Fmt.artifactName(root)
        // Where the lists this report caps can be read in full.
        val graphRef = if (siblings.graph) "`$an.graph.json`" else "the graph (`--json`)"
        L.add(
            "_Scanned ${Fmt.modelScale(s)}, " +
                "${Fmt.scalar(s["java"]) ?: "0"} Java files, ${Fmt.scalar(s["endpoints"]) ?: "0"} REST endpoints. " +
                "Generated by Flowable Atlas — regenerate with ${Siblings.GENERATE}." +
                // The SVGs are written by the same `--all` run but nothing ever mentioned them.
                (if (siblings.diagrams) " Diagrams of the models that carry layout: `$an.diagrams/*.svg`." else "") +
                "_\n"
        )
        val refs = FileRefs.of(result)
        refs.legend()?.let { L.add(it + "\n") }

        // Apps & inventory
        val apps = asList(result["apps"])
        if (apps.isNotEmpty()) {
            L.add("## 1. Apps\n")
            for (aAny in apps) {
                val a = asMap(aAny)
                L.add("### ${pyStr(a["name"])} (`${pyStr(a["key"])}`)${refs.tail(a["file"])}")
                if (truthy(a["description"])) L.add("> ${pyStr(a["description"])}")
                L.add(
                    Fmt.fields(
                        "palette" to Fmt.codeList(a["paletteDefinitionCategory"]),
                        "variables" to asList(a["variables"]).size.toString(),
                        "models" to asList(a["childModels"]).size.toString(),
                    ).let { "- $it" }
                )
                // A model in the app's own archive is named by its entry alone: the heading above already
                // says which archive, and repeating it on every child row was a tenth of a real report.
                val appArchive = (a["file"] as? String)?.takeIf { '!' in it }?.substringBefore('!')
                for (cmAny in asList(a["childModels"])) {
                    val cm = asMap(cmAny)
                    val norm = NORMALIZE_TYPE[cm["type"] as? String] ?: cm["type"]
                    val loc = asMap(result["modelIndex"])["${pyStr(norm)}:${pyStr(cm["key"])}"] as? String
                    val where = when {
                        loc.isNullOrEmpty() -> null
                        appArchive != null && loc.startsWith("$appArchive!") -> loc.substringAfter('!')
                        else -> refs.of(loc)
                    }
                    L.add(
                        "    - ${pyStr(cm["type"])} `${pyStr(cm["key"])}`" +
                            (if (where != null) " → `$where`" else " → _(not found)_")
                    )
                }
                L.add("")
            }
        }

        // Processes
        val processes = asList(result["processes"])
        if (processes.isNotEmpty()) {
            hdr(2, "Processes (BPMN)")
            for (pAny in processes) {
                renderProcess(asMap(pAny), L, refs)
            }
        }

        // Cases
        val cases = asList(result["cases"])
        if (cases.isNotEmpty()) {
            hdr(3, "Cases (CMMN)")
            for (cAny in cases) {
                renderCase(asMap(cAny), L, refs)
            }
        }

        // Decisions
        val decisions = asList(result["decisions"])
        if (decisions.isNotEmpty()) {
            hdr(4, "Decision tables (DMN)")
            for (dAny in decisions) {
                renderDecision(asMap(dAny), L, refs)
            }
            L.add("")
        }

        // Forms & Pages
        val forms = asList(result["forms"])
        if (forms.isNotEmpty()) {
            hdr(5, "Forms & pages")
            for (fAny in forms) {
                renderForm(asMap(fAny), L, graphRef, refs)
            }
        }

        // Data objects
        val dataObjects = asList(result["dataObjects"])
        if (dataObjects.isNotEmpty()) {
            L.add("## 5b. Data objects\n")
            for (dAny in dataObjects) {
                val d = asMap(dAny)
                val flds = asList(d["fields"])
                val preview = flds.take(12).joinToString(", ") { pyStr(it) } + (if (flds.size > 12) " …" else "")
                val table = if (truthy(d["serviceTableName"])) " (table `${pyStr(d["serviceTableName"])}`)" else ""
                L.add(
                    "- `${pyStr(d["key"])}` (${pyStr(orAny(d["dataObjectType"], "dataObject"))})$table " +
                        "[${flds.size} fields${if (truthy(preview)) ": $preview" else ""}]" + refs.tail(d["file"])
                )
            }
            L.add("")
        }

        // Data dictionaries
        val dictionaries = asList(result["dictionaries"])
        if (dictionaries.isNotEmpty()) {
            L.add("## 5c. Data dictionaries\n")
            for (dAny in dictionaries) {
                val d = asMap(dAny)
                // the type names as a code list, not a Python repr of the list (the first fixture with
                // a dictionary read "types: ['Address', 'Customer']")
                val types = Fmt.codeList(d["types"]).takeIf { it.isNotBlank() }?.let { " — types: $it" } ?: ""
                L.add("- `${pyStr(d["key"])}`$types" + refs.tail(d["file"]))
            }
            L.add("")
        }

        // Other models
        val others = asList(result["others"])
        if (others.isNotEmpty()) {
            L.add("## 5d. Other models (queries, templates, policies, sequences, …)\n")
            val byType = LinkedHashMap<String, MutableList<Map<String, Any?>>>()
            for (oAny in others) {
                val o = asMap(oAny)
                val mtype = pyStr(if (o.containsKey("modelType")) o["modelType"] else "?")
                byType.getOrPut(mtype) { mutableListOf() }.add(o)
            }
            for (mtype in byType.keys.sorted()) {
                L.add("**$mtype** (${byType[mtype]!!.size}):")
                for (o in byType[mtype]!!) {
                    L.add("- " + Fmt.join("`${pyStr(o["key"])}`", orE(o["name"])) + refs.tail(o["file"]))
                }
            }
            L.add("")
        }

        // Agents / Bots
        val agents = asList(result["agents"])
        if (agents.isNotEmpty()) {
            hdr(6, "AI agents & bots")
            for (aAny in agents) {
                val a = asMap(aAny)
                // Only what the model states: an agent without a type or a vendor used to read
                // "(None)" and "model: None/None (temp None)" — the fixture that first carried an agent
                // caught it.
                val type = Fmt.scalar(a["type"])?.takeIf { it.isNotEmpty() }?.let { " ($it)" } ?: ""
                L.add("### `${pyStr(a["key"])}` — ${orE(a["name"])}$type" + refs.tail(a["file"]))
                val model = listOfNotNull(Fmt.scalar(a["aiVendor"]), Fmt.scalar(a["modelName"]))
                    .filter { it.isNotEmpty() }.joinToString("/")
                val modelLine = Fmt.fields(
                    "model" to model,
                    "temperature" to (Fmt.scalar(a["temperature"]) ?: ""),
                    "apiEndpoint" to (Fmt.scalar(a["enableApiEndpoint"]) ?: ""),
                )
                if (modelLine.isNotBlank()) L.add("- $modelLine")
                if (truthy(a["knowledgeBase"])) L.add("- 📚 knowledgeBase → `${pyStr(a["knowledgeBase"])}`")
                for (tAny in asList(a["tools"])) {
                    val t = asMap(tAny)
                    L.add("- 🛠️ tool (${pyStr(t["type"])}) → `${pyStr(t["key"])}`")
                }
                for (opAny in asList(a["operations"])) {
                    val op = asMap(opAny)
                    L.add("- op `${pyStr(op["key"])}`: ${pyStr(orAny(op["systemMessage"], op["userMessage"], ""))}")
                }
                L.add("")
            }
        }

        // Integration
        hdr(7, "Integration: Services, Channels, Events & REST")
        val services = asList(result["services"])
        if (services.isNotEmpty()) {
            L.add("### Service models (.service)")
            for (svAny in services) {
                val sv = asMap(svAny)
                val attrs = Fmt.fields(
                    "base" to Fmt.codeList(sv["baseUrl"]),
                    "auth" to Fmt.list(sv["auth"]),
                    "table" to Fmt.codeList(sv["tableName"]),
                )
                L.add(
                    "- **${pyStr(orAny(sv["name"], sv["key"]))}** (" +
                        listOfNotNull("`${pyStr(sv["key"])}`", Fmt.scalar(sv["type"])?.ifEmpty { null }).joinToString(", ") + ")" +
                        (if (attrs.isEmpty()) "" else " · $attrs") + refs.tail(sv["file"])
                )
                for (opAny in asList(sv["operations"])) {
                    val op = asMap(opAny)
                    // in/out parameters are the operation's contract: without them a caller cannot be
                    // written, and they only ever appeared in the explorer.
                    val contract = Fmt.fields(
                        "in" to Fmt.codeList(asList(op["params"]).map { paramName(it) }.filter { it.isNotEmpty() }),
                        "out" to Fmt.codeList(asList(op["outParams"]).map { paramName(it) }.filter { it.isNotEmpty() }),
                    )
                    // A database operation has neither verb nor URL — 116 lines of one real report read
                    // "`None` None" — so it is named by its key and the kind of operation it is instead.
                    // A script operation calls no URL either: what it runs is its script, in its language.
                    val endpoint = if (op["script"] != null) {
                        Fmt.join("script", Fmt.scalar(op["scriptLanguage"])?.ifBlank { null }?.let { Fmt.code(it) } ?: "")
                    } else Fmt.join(
                        Fmt.scalar(op["method"])?.ifBlank { null }?.let { Fmt.code(it) } ?: "",
                        Fmt.scalar(orAny(op["fullUrl"], op["url"]))?.ifBlank { null }?.let { Fmt.code(it) } ?: "",
                    )
                    val opRef = "op `${pyStr(op["key"])}`"
                    val head = if (endpoint.isEmpty()) opRef + (Fmt.scalar(op["type"])?.ifBlank { null }?.let { " ($it)" } ?: "")
                        else "$endpoint ($opRef)"
                    L.add("    - $head" + (if (contract.isEmpty()) "" else " · $contract"))
                }
            }
            L.add("")
        }
        renderDataLayer(result, L, refs)
        val channels = asList(result["channels"])
        if (channels.isNotEmpty()) {
            L.add("### Channels (.channel)")
            for (chAny in channels) {
                val ch = asMap(chAny)
                val attrs = Fmt.fields(
                    "topics" to Fmt.codeList(ch["topics"]),
                    "destination" to Fmt.codeList(ch["destination"]),
                )
                L.add(
                    "- " + Fmt.join("`${pyStr(ch["key"])}`", listOfNotNull(Fmt.scalar(ch["channelType"]), Fmt.scalar(ch["type"]))
                        .filter { it.isNotEmpty() }.joinToString("/")) +
                        (if (attrs.isEmpty()) "" else " · $attrs") + refs.tail(ch["file"])
                )
            }
            L.add("")
        }
        val eventsList = asList(result["events"])
        if (eventsList.isNotEmpty()) {
            L.add("### Events (.event)")
            for (evAny in eventsList) {
                val ev = asMap(evAny)
                val attrs = Fmt.fields(
                    // payload entries are `{name, type, …}` records; the overview names them
                    "payload" to Fmt.codeList(asList(ev["payload"]).map { (it as? Map<*, *>)?.get("name") ?: it }),
                    "correlation" to Fmt.codeList(ev["correlation"]),
                )
                L.add("- `${pyStr(ev["key"])}`" + (if (attrs.isEmpty()) "" else " — $attrs"))
            }
            L.add("")
        }
        val restCalls = asList(result["restCalls"])
        if (restCalls.isNotEmpty()) {
            L.addAll(restCallsSection(restCalls))
            L.add("")
        }

        // Java glue
        hdr(8, "Java glue code")
        val javaGlue = asList(result["javaGlue"])
        if (javaGlue.isNotEmpty()) {
            L.add("### Delegates / listeners (model-referenced classes)")
            for (jcAny in javaGlue) {
                val jc = asMap(jcAny)
                val inter = (asList(jc["interfaces"]).mapNotNull { it as? String }.toSet() intersect GLUE_INTERFACES).sorted()
                // the interfaces only when it has one of them — "implements []" said nothing, as a list repr
                L.add("- `${pyStr(jc["fqn"])}`" + (if (inter.isEmpty()) "" else " implements ${inter.joinToString(", ")}") +
                    " — `${fileLine(jc)}`")
            }
            L.add("")
        }
        val javaControllers = asList(result["javaControllers"])
        if (javaControllers.isNotEmpty()) {
            L.add("### REST controllers & endpoints")
            for (jcAny in javaControllers) {
                val jc = asMap(jcAny)
                L.add("- **${pyStr(jc["primary"])}** — `${pyStr(jc["file"])}`")
                for (epAny in asList(jc["endpoints"])) {
                    val ep = asMap(epAny)
                    L.add("    - `${pyStr(ep["http"])}` ${pyStr(ep["path"])} → ${pyStr(ep["handler"])}() (line ${pyStr(ep["line"])})")
                }
            }
            L.add("")
        }

        // Model <-> code resolved references
        hdr(9, "Resolved references (model → code / model)")
        val resolvedRefs = asList(result["resolvedRefs"]).map { asMap(it) }
        val codeRefs = resolvedRefs.filter { it["targetType"] == "bean" || it["targetType"] == "class" }
        // An app's `contains` rows are §1's child lists said again — 254 of 737 rows on a real project —
        // and as the first rows in insertion order they pushed the references that say something past the cap.
        val modelRefs = resolvedRefs.filter { it["targetType"] == "model" && it["rel"] != "contains" }
        // Both lists are per-reference, so they grow with the project (478 lines on a real one) while
        // saying the same kind of thing over and over. Capped, with the full set a query away.
        if (codeRefs.isNotEmpty()) {
            L.add("### Model → Java code")
            for (r in codeRefs.take(RESOLVED_REFS_LISTED)) {
                L.add("- `${pyStr(r["from"])}` [${pyStr(r["rel"])}] `${pyStr(r["value"])}` → ${refs.of(r["target"])}")
            }
            if (codeRefs.size > RESOLVED_REFS_LISTED) {
                L.add("- … (+${codeRefs.size - RESOLVED_REFS_LISTED} more — `resolvedRefs` in " +
                    "$graphRef)")
            }
            L.add("")
        }
        if (modelRefs.isNotEmpty()) {
            L.add("### Model → Model")
            for (r in modelRefs.take(RESOLVED_REFS_LISTED)) {
                L.add("- `${pyStr(r["from"])}` —${pyStr(r["rel"])}→ ${pyStr(r["kind"])} `${pyStr(r["value"])}` (`${refs.of(r["target"])}`)")
            }
            if (modelRefs.size > RESOLVED_REFS_LISTED) {
                L.add("- … (+${modelRefs.size - RESOLVED_REFS_LISTED} more — `resolvedRefs` in " +
                    "$graphRef)")
            }
            L.add("")
        }

        // Unresolved
        hdr(10, "Unresolved references (external / library / missing)")
        val unresolvedRefs = asList(result["unresolvedRefs"]).map { asMap(it) }
        val groups = LinkedHashMap<Pair<String, String>, MutableList<Map<String, Any?>>>()
        for (r in unresolvedRefs) {
            groups.getOrPut(Pair(pyStr(r["kind"]), pyStr(r["value"]))) { mutableListOf() }.add(r)
        }
        val platform = groups.filterKeys { it.first == "bean" && it.second in Constants.FLOWABLE_PLATFORM_BEANS }
        val othersG = groups.filterKeys { it !in platform.keys }
        val tupleCmp = compareBy<Map.Entry<Pair<String, String>, *>>({ it.key.first }, { it.key.second })
        if (platform.isNotEmpty()) {
            L.add("### Expected Flowable platform beans (provided by the engine, not project code)")
            for ((k, rs) in platform.entries.sortedWith(tupleCmp)) {
                val n = rs.map { pyStr(it["from"]) }.toSet().size
                L.add("- `${k.second}` — referenced by $n model(s)")
            }
            L.add("")
        }
        if (othersG.isNotEmpty()) {
            L.add("### Other unresolved — review (external dependency, typo, or missing)")
            for ((k, rs) in othersG.entries.sortedWith(tupleCmp)) {
                val froms = rs.map { pyStr(it["from"]) }.toSortedSet().toList()
                val more = if (froms.size > 1) " (+${froms.size - 1} more)" else ""
                L.add("- [${k.first}] `${k.second}` — from `${froms[0]}`$more")
            }
            L.add("")
        }
        if (unresolvedRefs.isEmpty()) {
            // (not "None — …": the one word the hygiene test reads as a leaked Python repr)
            L.add("_Every reference resolved within the project._\n")
        }

        // Uncertain links — suspect (loose/cross-type) resolutions and dynamic (expression-valued)
        // references; both are rendered dashed in the explorer and deserve a review pass.
        val suspectRefs = asList(result["resolvedRefs"]).map { asMap(it) }.filter { it["suspect"] == true }
        if (suspectRefs.isNotEmpty()) {
            L.add("### Suspect links — resolved via a loose or cross-type match (verify)")
            for (r in suspectRefs) {
                val fb = r["fallbackType"]?.let { " — actually a `${pyStr(it)}` model" } ?: ""
                L.add("- `${pyStr(r["from"])}` —${pyStr(r["rel"])}→ ${pyStr(r["kind"])} `${pyStr(r["value"])}`$fb")
            }
            L.add("")
        }
        val dynRefs = asList(result["dynamicRefs"]).map { asMap(it) }
        if (dynRefs.isNotEmpty()) {
            L.add("### Dynamic references (expression-valued — resolved at runtime)")
            for (r in dynRefs.take(30)) {
                L.add("- `${pyStr(r["from"])}` —${pyStr(r["rel"])}→ ${pyStr(r["kind"])} `${pyStr(r["value"])}`")
            }
            if (dynRefs.size > 30) L.add("- … ${dynRefs.size - 30} more")
            L.add("")
        }

        // Access & user groups
        hdr(11, "Access & user groups (who can do what)")
        val acc = asList(result["access"]).map { asMap(it) }
        val groupsAll = asList(result["groups"])
        if (groupsAll.isNotEmpty()) {
            L.add(
                "**All groups/roles referenced (${groupsAll.size}):** " +
                    groupsAll.joinToString(", ") { "`${pyStr(it)}`" } + "\n"
            )
        }
        val appAcc = acc.filter { it["scope"] == "app" || it["scope"] == "page" }
        if (appAcc.isNotEmpty()) {
            L.add("### App / page access")
            for (a in appAcc) {
                val who0 = asList(a["groups"]).map { pyStr(it) } + asList(a["users"]).map { "user:${pyStr(it)}" }
                val who = if (who0.isNotEmpty()) who0.joinToString(", ") else "(everyone)"
                L.add("- ${pyStr(a["modelType"])} `${pyStr(a["model"])}`: $who")
            }
            L.add("")
        }
        val starts = acc.filter { it["action"] == "start" }
        if (starts.isNotEmpty()) {
            L.add("### Who can start (processes & cases)")
            for (a in starts.sortedBy { pyStr(it["model"]) }) {
                val who0 = asList(a["groups"]).map { pyStr(it) } + asList(a["users"]).map { pyStr(it) }
                val who = if (who0.isNotEmpty()) who0.joinToString(", ") else "(no restriction)"
                L.add("- ${pyStr(a["modelType"])} `${pyStr(a["model"])}` ← $who")
            }
            L.add("")
        }
        val assigns = acc.filter { it["action"] == "assign" }
        if (assigns.isNotEmpty()) {
            L.add("### Task assignment (candidate groups / assignees per model)")
            val bym = LinkedHashMap<String, MutableSet<String>>()
            for (a in assigns) {
                val set = bym.getOrPut(pyStr(a["model"])) { mutableSetOf() }
                set.addAll(asList(a["groups"]).map { pyStr(it) })
                set.addAll(asList(a["users"]).map { pyStr(it) })
            }
            for (model in bym.keys.sorted()) {
                L.add("- `$model`: ${bym[model]!!.sorted().joinToString(", ")}")
            }
            L.add("")
        }
        val doAcc = acc.filter { it["modelType"] == "dataObject" }
        if (doAcc.isNotEmpty()) {
            L.add("### Data object access (who may query/create/update/delete)")
            val bym = LinkedHashMap<String, MutableList<Map<String, Any?>>>()
            for (a in doAcc) bym.getOrPut(pyStr(a["model"])) { mutableListOf() }.add(a)
            for (model in bym.keys.sorted()) {
                val perms = bym[model]!!.joinToString("; ") { a ->
                    val g = asList(a["groups"]).joinToString("/") { pyStr(it) }
                    "${pyStr(a["action"])}=${if (g.isNotEmpty()) g else "?"}"
                }
                L.add("- `$model`: $perms")
            }
            L.add("")
        }
        val policies = asList(result["policies"]).map { asMap(it) }
        if (policies.isNotEmpty()) {
            L.add("### Security policies")
            for (p in policies) {
                L.add("- `${pyStr(p["key"])}`" + refs.tail(p["file"]))
                for (permAny in asList(p["permissions"])) {
                    val perm = asMap(permAny)
                    val roles = asList(perm["roles"]).map { pyStr(it) }
                    L.add("    - ${pyStr(perm["key"])}: ${if (roles.isNotEmpty()) roles.joinToString(", ") else "(none)"}")
                }
            }
            L.add("")
        }
        if (acc.isEmpty() && policies.isEmpty()) {
            L.add("_No explicit access restrictions found._\n")
        }

        // Code map
        hdr(12, "Code map (where things live)")
        if (agents.isNotEmpty()) {
            L.add("**Agents / bots (models):**")
            for (aAny in agents) {
                val a = asMap(aAny)
                L.add("- `${pyStr(a["key"])}`" + refs.tail(a["file"]))
            }
        }
        // (The service models were listed here a second time — key, type, table and file, all in §7.)
        // Models grouped by folder
        val folders = LinkedHashMap<String, LinkedHashMap<String, Int>>()
        val bucketLabel = listOf(
            "processes" to "bpmn", "cases" to "cmmn", "decisions" to "dmn",
            "forms" to "form", "dataObjects" to "data", "services" to "service",
            "agents" to "agent", "channels" to "channel", "events" to "event",
            "dictionaries" to "dict", "policies" to "policy", "actions" to "action",
            "liquibase" to "liquibase", "others" to "other",
        )
        for ((bucket, label) in bucketLabel) {
            for (oAny in asList(result[bucket])) {
                val o = asMap(oAny)
                val fpath = (o["file"] as? String) ?: ""
                val head = fpath.split("!")[0]
                val folder = if (head.contains("/")) head.substringBeforeLast("/") else "."
                val fm = folders.getOrPut(folder) { LinkedHashMap() }
                fm[label] = (fm[label] ?: 0) + 1
            }
        }
        if (folders.isNotEmpty()) {
            L.add("\n**Models by folder:**")
            for (folder in folders.keys.sorted()) {
                val counts = folders[folder]!!.entries
                    .sortedWith(compareBy({ it.key }, { it.value }))
                    .joinToString(", ") { "${it.value} ${it.key}" }
                L.add("- `$folder/` — $counts")
            }
        }
        // Java by role
        val jbr = asMap(result["javaByRole"])
        if (jbr.isNotEmpty()) {
            L.add("\n**Java code by role:**")
            for (role in listOf(
                "controller", "delegate", "listener", "service", "repository",
                "configuration", "component", "other",
            )) {
                val items = asList(jbr[role])
                if (items.isEmpty()) continue
                if (role == "other") {
                    L.add("\n_other (no Spring/Flowable role — DTOs, utils, …): ${items.size} classes_")
                    continue
                }
                L.add("\n_$role (${items.size}):_")
                for (jc in items.map { asMap(it) }.sortedBy { pyStr(it["fqn"]) }.take(80)) {
                    var iface = ""
                    if (role == "delegate" || role == "listener") {
                        val rel = asList(jc["interfaces"]).mapNotNull { it as? String }
                            .filter { it.endsWith("Listener") || it in GLUE_INTERFACES }.sorted()
                        iface = if (rel.isNotEmpty()) " [${rel.joinToString(", ")}]" else ""
                    }
                    L.add("- `${pyStr(jc["fqn"])}`$iface — `${fileLine(jc)}`")
                }
                if (items.size > 80) L.add("- … (+${items.size - 80} more)")
            }
        }
        L.add("")

        // Variables / expressions
        hdr(13, "Variables, beans & expressions")
        renderVariables(result, L)
        val beans = asList(result["beans"])
        if (beans.isNotEmpty()) {
            L.add("**Beans/objects with method calls:** " + beans.joinToString(", ") { "`${pyStr(it)}`" } + "\n")
        }
        val delegateClasses = asList(result["delegateClasses"])
        if (delegateClasses.isNotEmpty()) {
            L.add(
                "**JavaDelegate/listener classes referenced:** " +
                    delegateClasses.joinToString(", ") { "`${pyStr(it)}`" } + "\n"
            )
        }
        renderExpressions(result, L, graphRef)

        // Node types this report does not have a section for. Several of them are the answer to a common
        // question — `serviceOperation.usedBy` is "who calls this operation", `method` is "which Java
        // method does this expression reach", the correlation types are "who throws this signal" — and
        // saying nothing about them left a reader assuming the report was the whole graph.
        val counts = LinkedHashMap<String, Int>()
        for (nAny in asList(asMap(result["graph"])["nodes"])) {
            val t = asMap(nAny)["type"]?.toString() ?: continue
            if (t in REPORTED_NODE_TYPES) continue
            counts[t] = (counts[t] ?: 0) + 1
        }
        if (counts.isNotEmpty()) {
            L.add("**Also in the graph** (queryable in $graphRef, no section here): " +
                counts.entries.sortedByDescending { it.value }.joinToString(" · ") { "${it.value} ${it.key}" } +
                ".\n")
        }

        // Findings — what is probably wrong, itemized. Computed in `Findings.kt`; before that these
        // checks lived only in the explorer's JavaScript, so no text artifact could state any of them.
        val findings = asList(result["findings"]).map { asMap(it) }
        val checks = asMap(result["checks"])
        val waivedFindings = findings.filter { it["waived"] != null }
        val openFindings = findings.filter { it["waived"] == null }
        val labels by lazy { Fmt.nodeLabels(result) }
        if (findings.isNotEmpty()) {
            val open = (checks["open"] as? Number)?.toInt() ?: openFindings.size
            val headline = Fmt.healthHeadline(asMap(result["stats"])).ifEmpty { "$open open" }
            hdr(14, "Findings — $headline" + if (waivedFindings.isNotEmpty()) ", ${waivedFindings.size} waived" else "")
            L.addAll(Fmt.healthLines(checks))
            L.add("")
            // Defects first, then advice under a line that says what changes at the border: the reader
            // of §14 is asking "what is wrong", and everything below that line is not wrong.
            var adviceStarted = false
            for ((check, group) in openFindings.groupBy { it["check"]?.toString() ?: "?" }) {
                if (!adviceStarted && CheckCatalog.kind(check) == CheckCatalog.ADVICE) {
                    adviceStarted = true
                    L.add("*Advice — nothing below is broken; each is a pattern worth a look.*")
                    L.add("")
                }
                L.add("**${CheckCatalog.label(check)}** (${group.size})")
                for (f in group.take(FINDINGS_PER_CHECK)) {
                    val mark = if (f["severity"] == "error") "⚠" else "·"
                    // A parse finding's label *is* its file — don't print the same path twice.
                    val fileText = f["file"]?.toString()?.takeIf { it != f["label"]?.toString() }
                        ?.let { refs.of(it) }?.let { if (truthy(f["line"])) "$it:${pyStr(f["line"])}" else it }
                    // An expression finding's label is the expression: it is *at* that text, *in* the
                    // models that hold it.
                    val models = Fmt.findingModels(f, labels).removePrefix("in ")
                    val where = Fmt.fields(
                        "in" to models.ifEmpty { Fmt.codeList(f["label"]) },
                        "at" to Fmt.codeList(f["element"] ?: f["label"].takeIf { models.isNotEmpty() }),
                        "file" to Fmt.codeList(fileText),
                        // a script line no file line could be found for: within the script body
                        "script line" to (f["scriptLine"]?.let { pyStr(it) } ?: ""),
                    )
                    L.add("- $mark ${pyStr(f["message"])}" + (if (where.isEmpty()) "" else " — $where"))
                    if (truthy(f["snippet"])) L.add("    " + Fmt.code(pyStr(f["snippet"])))
                }
                if (group.size > FINDINGS_PER_CHECK) {
                    L.add("- … (+${group.size - FINDINGS_PER_CHECK} more — see `findings` in " +
                        "$graphRef)")
                }
                L.add("")
            }
        }

        // Accepted findings get their own block rather than a strike-through in the list above: the
        // reader of §14 is asking "what is wrong", and the answer to "what did we decide to live with,
        // and why" is a different question that deserves its own heading — and its reasons.
        if (waivedFindings.isNotEmpty()) {
            L.add("**Waived — deliberately accepted (${waivedFindings.size})**")
            L.add("")
            for (f in waivedFindings.take(FINDINGS_PER_CHECK * 2)) {
                val reason = (f["waived"] as? Map<*, *>)?.get("reason")?.toString().orEmpty()
                val where = Fmt.fields("in" to Fmt.codeList(f["label"]), "at" to Fmt.codeList(f["element"]))
                L.add("- ${pyStr(f["message"])}" + (if (where.isEmpty()) "" else " — $where") +
                    (if (reason.isBlank()) " — *no reason given*" else " — accepted: $reason"))
            }
            if (waivedFindings.size > FINDINGS_PER_CHECK * 2) {
                L.add("- … (+${waivedFindings.size - FINDINGS_PER_CHECK * 2} more — see `findings` in $graphRef)")
            }
            L.add("")
        }
        // What the waiver file itself got wrong, where the people who maintain it will read it.
        asMap(result["waivers"]).let { w ->
            val notices = asList(w["stale"]).map { pyStr(it) } + asList(w["unexplained"]).map { pyStr(it) } +
                asList(w["problems"]).map { pyStr(it) }
            if (notices.isNotEmpty()) {
                L.add("**Waiver file needs attention (${notices.size})**")
                L.add("")
                for (n in notices) L.add("- $n")
                L.add("")
            }
        }

        // (There used to be a §14 "Warnings" section here listing `result.warnings`. Those are the same
        // parse/read failures the findings above now report as `unparseable files`, with their file and
        // message — so the section only repeated itself. `warnings`/`diagnostics` remain in graph.json.)
        return L.joinToString("\n")
    }

    /**
     * One process as the report lists it: its heading, then every element in execution order with what
     * follows it. A function of its own so `--slice` can show a process's contents exactly as the report
     * does — two renderings of one model would drift, and the overview golden pins this one.
     */
    internal fun renderProcess(p: Map<String, Any?>, L: MutableList<String>, refs: FileRefs = FileRefs.NONE) {
        L.add("### ${orE(p["name"])} (`${pyStr(p["key"])}`)" + refs.tail(p["file"]))
        if (truthy(p["documentation"])) L.add("> ${pyStr(p["documentation"])}")
        if (truthy(p["candidateStarterGroups"]))
            L.add("- starter groups: `${pyStr(p["candidateStarterGroups"])}`")
        // Elements are collected first and emitted in **execution order** (see [flowOrder]).
        // Grouped-by-type listing put the start and end events last and left a reader unable to
        // tell what runs after what — the first thing anyone needs to know about a process.
        // `id` is not unique across buckets (a DMN service task is both a serviceTask and a
        // ruleTask), so rows are a list, not a map, and sorting is stable.
        val rows = ArrayList<Triple<String, String, Boolean>>() // (elementId, line, isSubLine)
        var synthetic = 0
        fun row(id: Any?, line: String) {
            rows.add(Triple(if (truthy(id)) pyStr(id) else "?unnamed-${synthetic++}", line, false))
        }
        fun subRow(id: Any?, line: String) {
            if (truthy(id)) rows.add(Triple(pyStr(id), line, true))
        }

        for (utAny in asList(p["userTasks"])) {
            val ut = asMap(utAny)
            val extra = if (truthy(ut["formKey"])) " form=`${pyStr(ut["formKey"])}`" else ""
            row(
                ut["id"],
                Fmt.join(
                    "- 👤 ${DesignTerms.label("el", "userTask")} `${pyStr(ut["id"])}`",
                    orE(ut["name"]), extra,
                    if (truthy(ut["assignee"])) "assignee=${pyStr(ut["assignee"])}" else "",
                )
            )
        }
        for (stAny in asList(p["serviceTasks"])) {
            val st = asMap(stAny)
            val impl = orAny(st["class"], st["delegateExpression"], st["expression"], st["type"], "?")
            val rv = if (truthy(st["resultVariable"])) " → var `${pyStr(st["resultVariable"])}`" else ""
            row(st["id"], "- ⚙️ ${DesignTerms.label("el", "serviceTask")} `${pyStr(st["id"])}` " +
                "${orE(st["name"])} → ${pyStr(impl)}$rv${ioSuffix(p, st["id"])}")
        }
        // Script tasks were missing from this report entirely — a process could run a script and
        // nothing in the Markdown said so.
        for (stAny in asList(p["scriptTasks"])) {
            val st = asMap(stAny)
            val fmt = if (truthy(st["format"])) " (${pyStr(st["format"])})" else ""
            val rv = if (truthy(st["resultVariable"])) " → var `${pyStr(st["resultVariable"])}`" else ""
            val probs = asList(st["problems"])
            val warn = if (probs.isEmpty()) ""
                else " — ⚠ ${probs.size} syntax finding${if (probs.size > 1) "s" else ""}"
            row(st["id"], "- 🧾 ${DesignTerms.label("el", "scriptTask")} `${pyStr(st["id"])}` " +
                "${orE(st["name"])}$fmt$rv$warn")
        }
        for (rtAny in asList(p["ruleTasks"])) {
            val rt = asMap(rtAny)
            row(rt["id"], "- 📊 ${DesignTerms.label("el", "serviceTask/dmn")} `${pyStr(rt["id"])}` " +
                "→ decision table `${pyStr(rt["decisionRef"])}`")
        }
        // Gateways and receive/send/manual tasks are parsed but were never rendered: a branch
        // point missing from the listing makes the flow below it unreadable.
        for (gwAny in asList(p["gateways"])) {
            val gw = asMap(gwAny)
            row(gw["id"], Fmt.join(
                "- ◆ ${DesignTerms.label("el", gw["type"])} `${pyStr(gw["id"])}`", orE(gw["name"]),
            ))
        }
        for (otAny in asList(p["otherTasks"])) {
            val ot = asMap(otAny)
            row(ot["id"], Fmt.join(
                "- ▫ ${DesignTerms.label("el", ot["type"])} `${pyStr(ot["id"])}`", orE(ot["name"]),
            ))
        }
        for (spAny in asList(p["subProcesses"])) {
            val sp = asMap(spAny)
            row(sp["id"], Fmt.join(
                "- ▣ ${DesignTerms.label("el", orAny(sp["type"], "subProcess"))} `${pyStr(sp["id"])}`",
                orE(sp["name"]),
            ))
        }
        for (caAny in asList(p["callActivities"])) {
            val ca = asMap(caAny)
            row(ca["id"], "- 📞 ${DesignTerms.label("el", "callActivity")} `${pyStr(ca["id"])}` " +
                "→ process `${pyStr(ca["calledElement"])}`${ioSuffix(p, ca["id"])}")
        }
        for (miAny in asList(p["multiInstance"])) {
            val mi = asMap(miAny)
            // Parallel or one after the other is the first thing to know about a multi-instance step, and
            // a loop counted by `loopCardinality` has no collection — that line used to end in nothing.
            // (toString, not Fmt.scalar: a boolean there would read "yes", and "sequential if `yes`")
            val seq = mi["sequential"]?.toString()?.trim().orEmpty()
            val mode = when {
                seq.isEmpty() || seq.equals("false", ignoreCase = true) -> "parallel"
                seq.equals("true", ignoreCase = true) -> "sequential"
                else -> "sequential if ${Fmt.code(seq)}"
            }
            val attrs = Fmt.fields(
                "cardinality" to Fmt.codeList(mi["cardinality"]),
                "collection" to Fmt.codeList(mi["collection"]),
                "elementVar" to Fmt.codeList(mi["elementVariable"]),
                "completes when" to (Fmt.scalar(mi["completionCondition"])?.ifBlank { null }?.let { Fmt.code(it) } ?: ""),
            )
            subRow(mi["activity"], "    - 🔁 Multi-instance ($mode)" + (if (attrs.isEmpty()) "" else " · $attrs"))
        }
        for (evAny in asList(p["events"])) {
            val ev = asMap(evAny)
            val d = if (truthy(ev["def"]))
                " (${pyStr(ev["def"])}${if (truthy(ev["value"])) "=" + pyStr(ev["value"]) else ""})"
            else ""
            // A boundary event is part of the activity it hangs on: say which, and whether firing it
            // cancels that activity (Flowable's default) or leaves it open.
            val host = if (ev["type"] == "boundaryEvent") Fmt.scalar(ev["attachedTo"])?.ifBlank { null } else null
            row(ev["id"], Fmt.join(
                "- 🔔 ${DesignTerms.label("el", ev["type"])}$d `${pyStr(ev["id"])}`", orE(ev["name"]),
                host?.let { "on `$it`" } ?: "",
                if (host != null && Fmt.scalar(ev["cancelActivity"]) == "false") "(non-interrupting)" else "",
            ))
        }
        // Listeners of the process AND of its elements. Only the process-level ones were listed,
        // and a script-only listener was skipped entirely because it has no class/expression —
        // both cases hid code that runs at runtime.
        // Element listeners now sit under their element instead of in one block at the end, so a
        // reader sees the code that runs at a step next to the step.
        for (bucket in ELEMENT_BUCKETS) {
            for (elAny in asList(p[bucket])) {
                val el = asMap(elAny)
                for (lsAny in asList(el["listeners"])) {
                    listenerLine(asMap(lsAny))?.let { subRow(el["id"], "    - $it") }
                }
            }
        }

        // --- emit in execution order, each step naming what follows it ---
        val order = flowOrder(p, rows.map { it.first }.distinct())
        val successors = successorsByElement(p)
        val ordered = rows.sortedWith(
            compareBy({ order[it.first] ?: Int.MAX_VALUE }, { if (it.third) 1 else 0 })
        )
        // An element no sequence flow mentions is *not* the next step of the line above it, even
        // though document order lands it there — say so rather than imply a sequence that the
        // model does not have. (Only worth saying when the process has flows at all.)
        val connected = HashSet<String>()
        for (fAny in asList(p["flows"])) {
            val f = asMap(fAny)
            f["from"]?.toString()?.let { connected.add(it) }
            f["to"]?.toString()?.let { connected.add(it) }
        }
        val hasFlows = connected.isNotEmpty()
        // Reached by an event rather than a flow, so no flow mentioning them is no sign of a dead end: a
        // boundary event fires on its activity (unreachable only if that is), an event sub-process starts
        // whenever its event arrives.
        val boundaryHost = asList(p["events"]).map { asMap(it) }.filter { it["type"] == "boundaryEvent" }
            .mapNotNull { e -> Fmt.scalar(e["id"])?.let { id -> Fmt.scalar(e["attachedTo"])?.let { id to it } } }.toMap()
        val eventSubs = asList(p["subProcesses"]).map { asMap(it) }.filter { it["eventSubProcess"] == true }
            .mapNotNull { Fmt.scalar(it["id"]) }.toSet()
        val annotated = HashSet<String>()
        for ((id, line, sub) in ordered) {
            if (sub) { L.add(line); continue }
            val next = successors[id]
            // The same id can be described by two rows (a DMN service task is both); the
            // successor belongs to the element, so state it once.
            val suffix = when {
                !annotated.add(id) -> ""
                !next.isNullOrEmpty() -> " · next: ${Fmt.cap(next, 6)}"
                !hasFlows || id in connected -> ""
                id in eventSubs -> " · _(starts on its event)_"
                boundaryHost[id]?.let { it in connected } == true -> ""
                else -> " · _(no sequence flow — not reachable)_"
            }
            L.add(line + suffix)
        }
        // Process-level listeners are not steps, so they follow the flow rather than interrupt it.
        for (lsAny in asList(p["listeners"])) listenerLine(asMap(lsAny))?.let { L.add("- $it") }
        L.add("")
    }

    /** One case: its heading, the models it references, the plan tree with each criterion's condition. */
    internal fun renderCase(c: Map<String, Any?>, L: MutableList<String>, refs: FileRefs = FileRefs.NONE) {
        L.add("### ${orE(c["name"])} (`${pyStr(c["key"])}`)" + refs.tail(c["file"]))
        if (truthy(c["documentation"])) L.add("> ${pyStr(c["documentation"])}")
        for (mrAny in asList(c["modelRefs"])) {
            val mr = asMap(mrAny)
            L.add("- ${pyStr(mr["rel"])}: `${pyStr(mr["key"])}`")
        }
        // Index the sentries so the plan tree can show each criterion's actual condition.
        val sentryIndex = asList(c["sentries"]).map { asMap(it) }
            .mapNotNull { sen -> sen["id"]?.toString()?.ifEmpty { null }?.let { it to sen } }
            .toMap()
        val tree = CaseTree(c, sentryIndex)
        if (truthy(c["planModel"])) {
            val plan = asMap(c["planModel"])
            // The plan model's own exit criteria end the whole case, and no plan item carries them.
            val exits = criteriaText(asList(plan["exitCriteria"]).map { asMap(it) }, tree)
            // Depth 0: indented under the heading, the tree was a code block to any Markdown reader.
            renderStage(plan, L, 0, tree, exits)
        }
        val unused = asList(c["sentries"]).map { asMap(it) }.filter { it["id"]?.toString() !in tree.shown }
        if (unused.isNotEmpty()) {
            L.add("- 🚪 Sentries no plan item uses:")
            for (sen in unused) {
                L.add("    - " + Fmt.join("`${pyStr(sen["id"])}`", sentryText(sen, tree)))
            }
        }
        for (eAny in asList(c["eventListeners"])) {
            val e = asMap(eAny)
            val t = if (truthy(e["timer"])) " timer=`${pyStr(e["timer"])}`" else ""
            L.add("- ⏰ ${DesignTerms.label("el", e["type"])} `${pyStr(e["id"])}`$t")
        }
        // the case's own lifecycle listeners, as a process's listeners follow its flow
        for (lsAny in asList(c["listeners"])) listenerLine(asMap(lsAny))?.let { L.add("- $it") }
        L.add("")
    }

    /** One decision table: its signature line and the rule rows, capped at [DMN_RULES_LISTED]. */
    internal fun renderDecision(d: Map<String, Any?>, L: MutableList<String>, refs: FileRefs = FileRefs.NONE) {
        // A DRD decision without a table has no hit policy, rule count or columns; it read
        // "(None, None rules) — in:  → out:".
        val count = (d["ruleCount"] as? Number)?.toInt()
        val shape = if (d["hitPolicy"] == null && count == null) "no decision table"
            else listOfNotNull(Fmt.scalar(d["hitPolicy"]), count?.let { "$it rule" + if (it == 1) "" else "s" })
                .joinToString(", ")
        val ins = Fmt.codeList(d["inputs"])
        val outs = Fmt.codeList(d["outputs"])
        val io = if (ins.isNotEmpty() && outs.isNotEmpty()) "in: $ins → out: $outs"
            else Fmt.fields("in" to ins, "out" to outs)
        L.add("- `${pyStr(d["key"])}` ($shape)" + (if (io.isEmpty()) "" else " — $io") + refs.tail(d["file"]))
        // The rule rows — the actual business logic. They were parsed into `rules` and then only
        // ever shown in the explorer, so the report described a decision table without saying
        // what it decides.
        val rules = asList(d["rules"]).map { asMap(it) }
        for (r in rules.take(DMN_RULES_LISTED)) {
            val ins = Fmt.list(r["inputs"], " · ")
            val outs = Fmt.list(r["outputs"], " · ")
            val note = if (truthy(r["annotation"])) " _(${pyStr(r["annotation"])})_" else ""
            L.add("    - when ${ins.ifEmpty { "—" }} → ${outs.ifEmpty { "—" }}$note")
        }
        if (rules.size > DMN_RULES_LISTED) {
            L.add("    - … (+${rules.size - DMN_RULES_LISTED} more rules)")
        }
        if (d["rulesTruncated"] == true) {
            L.add("    - _(rule list truncated during parsing — see the model file)_")
        }
    }

    /**
     * One form or page: its heading, its fields with what each button does, its outcomes and data
     * sources. [graphRef] is where the fields past the cap can be looked up; [fieldsListed] is that cap,
     * which the report needs to stay a report and a slice does not — it is the page of this one form, and
     * sending its reader to the graph for the last seven fields defeats it.
     */
    internal fun renderForm(
        f: Map<String, Any?>, L: MutableList<String>, graphRef: String, refs: FileRefs = FileRefs.NONE,
        fieldsListed: Int = FORM_FIELDS_LISTED,
    ) {
        L.add("### ${orE(f["name"])} (`${pyStr(f["key"])}`)" + refs.tail(f["file"]))
        val fields = asList(f["fields"])
        for (fldAny in fields.take(fieldsListed)) {
            val fld = asMap(fldAny)
            val label = orE(fld["label"])
            // A link button's caption *is* its `value`, so printing both says it twice.
            val b = if (truthy(fld["value"]) && pyStr(fld["value"]) != label)
                "← `${pyStr(fld["value"])}`" else ""
            val req = if (truthy(fld["required"])) "*(req)*" else ""
            // A button's line has to say what pressing it does: the model it invokes, and — on an
            // expression button — the expression it evaluates. Without those, a form's own section
            // named the button and left the reader to guess which action it was that the
            // references list said the form triggers. A data-source component's callee and a
            // button's endpoint are left out: the Data sources and REST calls lists below already
            // name both, and repeating them here only costs a reader tokens.
            val callee = asMap(fld["callee"])
            val to = if (truthy(callee["key"]) && callee["kind"] != "rest" &&
                fld["type"] in ModelJsonReader.BUTTON_TYPES)
                "→ ${pyStr(callee["kind"])} `${pyStr(callee["key"])}`" else ""
            val settings = asMap(fld["settings"])
            val script = settings["script"]
            val ex = if (truthy(script)) "= `${oneLine(script)}`" else ""
            L.add("- " + Fmt.join("`${pyStr(fld["id"])}`", "[${pyStr(fld["type"])}]",
                label, req, b, to, ex, gates(settings)))
        }
        if (fields.size > fieldsListed) {
            L.add("- … (+${fields.size - fieldsListed} more fields — `fields` on the form " +
                "node in $graphRef)")
        }
        val outcomes = asList(f["outcomes"])
        if (outcomes.isNotEmpty()) {
            L.add(
                "- outcomes: " + outcomes.map { asMap(it) }.filter { truthy(it["value"]) }
                    .joinToString(", ") { "`${pyStr(it["value"])}`" }
            )
        }
        // Once each, with how many components share it: nine selects on one placeholder URL were nine
        // identical lines, between which the eight real sources had to be found.
        val sources = asList(f["dataSources"]).map { Fmt.dataSource(it) }
        for ((source, n) in sources.groupingBy { it }.eachCount()) {
            L.add("- 🔌 data source: $source" + if (n > 1) " ×$n" else "")
        }
        for (sfAny in asList(f["subforms"])) {
            L.add("- 📑 subform → `${pyStr(sfAny)}`")
        }
        L.add("")
    }

    /** The per-element-type lists of a parsed process; anything an element can carry lives in one of them. */
    private val ELEMENT_BUCKETS = listOf(
        "userTasks", "serviceTasks", "scriptTasks", "ruleTasks", "callActivities",
        "subProcesses", "events", "gateways", "otherTasks",
    )

    /**
     * The data layer as one chain: **service ↔ Liquibase table ↔ data object**, column by column.
     *
     * `LiquibaseCoverage` replays the changelogs, matches every column against the service mapping and
     * the data objects that consume it, and records changelog authority (live / copy / superseded / orphan). It
     * is the most expensive analysis in `:core` — and its result reached only the HTML explorer's schema
     * tab. A report that lists a service, a data object and a changelog separately leaves the reader to
     * work out whether they actually line up, which is the one thing the analysis already knows.
     *
     * Only the rows that do *not* line up are listed: `ok` rows are covered by the count, while a gap is
     * the thing worth a line.
     */
    @Suppress("UNCHECKED_CAST")
    private fun renderDataLayer(result: Map<String, Any?>, L: MutableList<String>, refs: FileRefs) {
        val services = asList(result["services"]).map { asMap(it) }
            .filter { truthy(asMap(it["schemaCoverage"])) }
        val changelogs = asList(result["liquibase"]).map { asMap(it) }
        if (services.isEmpty() && changelogs.none { truthy(asMap(it["authority"])["status"]) }) return

        L.add("### Data layer — service ↔ Liquibase table ↔ data object")
        for (sv in services) {
            val cov = asMap(sv["schemaCoverage"])
            val counts = asMap(cov["counts"])
            val ok = (counts["ok"] as? Number)?.toInt() ?: 0
            val total = (counts["total"] as? Number)?.toInt() ?: 0
            L.add(
                "- **${pyStr(orAny(sv["name"], sv["key"]))}** (`${pyStr(sv["key"])}`) → " +
                    Fmt.join(
                        "table ${Fmt.codeList(cov["table"])}",
                        if (truthy(cov["liquibase"])) "· changelog ${Fmt.codeList(cov["liquibase"])}" else "",
                        "· $ok/$total columns mapped end-to-end",
                        if (truthy(cov["dataObjects"])) "· data objects ${Fmt.codeList(cov["dataObjects"])}" else "",
                    )
            )
            val gaps = (cov["rows"] as? List<Map<String, Any?>> ?: emptyList())
                .filter { it["status"] != "ok" }
            for (r in gaps.take(SCHEMA_ROWS_LISTED)) {
                val what = when (r["status"]) {
                    "no-service" -> "in Liquibase only — the service does not map it"
                    "no-dataobject" -> "mapped by the service but no data object uses it"
                    "extra-service" -> asMap(r["removed"]).takeIf { it.isNotEmpty() }?.let { rm ->
                        val by = asMap(rm["by"])
                        (if (truthy(rm["renamedTo"])) "renamed to `${pyStr(rm["renamedTo"])}`" else "dropped") +
                            " by change set `${pyStr(by["changeSet"])}` of `${pyStr(by["file"])}`, yet mapped by the service"
                    } ?: "mapped by the service but not in any changelog"
                    else -> pyStr(r["status"])
                }
                val sqlType = Fmt.list(r["sqlType"]).let { if (it.isEmpty()) "" else " ($it)" }
                L.add("    - ⚠ ${Fmt.codeList(r["sql"])}$sqlType — $what")
            }
            if (gaps.size > SCHEMA_ROWS_LISTED) {
                L.add("    - … (+${gaps.size - SCHEMA_ROWS_LISTED} more gap(s))")
            }
        }
        // Changelogs whose authority is in doubt: an orphan nobody references, or one a later changelog
        // has superseded. Deploying against the wrong one is a silent schema drift.
        for (cl in changelogs) {
            val auth = asMap(cl["authority"])
            val status = auth["status"]?.toString() ?: continue
            // a copy of the application's own changelog is the same changelog, not one in doubt
            if (status == "live" || status == "copy") continue
            val detail = when (status) {
                "superseded" -> "superseded by ${Fmt.codeList(auth["supersededBy"])}"
                "orphan" -> if (truthy(auth["namesMissing"])) "names ${Fmt.codeList(auth["namesMissing"])}, which the project does not define"
                    else "referenced by no service or data object"
                else -> status
            }
            L.add("- ⚠ changelog `${pyStr(cl["key"])}` — $detail" + refs.tail(cl["file"]))
        }
        L.add("")
    }

    /**
     * The REST calls the models make, **one line per distinct call** (method and URL), in three groups.
     *
     * Every call used to be a line of its own, and every one that matched no controller carried "no
     * matching controller in project (external or unimplemented)". On a real project 174 of 203 calls
     * were flagged, 128 of them calls to Flowable's own API (`{{endpoints.idm}}/users/{{$id}}` from every
     * user picker), which no project implements; an agent reading "unimplemented" next to them might go
     * and write a controller. Now the warning is kept for the one case where it can be true — a call on
     * the application's own base that nothing here serves — and Flowable's API and other systems are
     * listed apart, once per URL, with who calls them. The split is [JavaParser.callTarget], the rule the
     * matcher itself applies.
     */
    internal fun restCallsSection(restCalls: List<Any?>): List<String> {
        val groups = LinkedHashMap<Pair<String?, String?>, MutableList<Map<String, Any?>>>()
        for (rcAny in restCalls) {
            val rc = asMap(rcAny)
            groups.getOrPut(Fmt.scalar(rc["method"])?.ifBlank { null } to Fmt.scalar(rc["url"])?.ifBlank { null }) { ArrayList() }
                .add(rc)
        }
        val own = ArrayList<String>()
        val flowable = ArrayList<String>()
        val elsewhere = ArrayList<String>()
        for ((key, calls) in groups) {
            val (method, url) = key
            val call = Fmt.join(method?.let { Fmt.code(it) } ?: "", url?.let { Fmt.code(it) } ?: "")
            val callers = calls.map { rc ->
                val src = listOfNotNull(Fmt.scalar(rc["source"]), Fmt.scalar(rc["where"])?.ifBlank { null }).joinToString("/")
                Fmt.join(Fmt.scalar(rc["kind"]) ?: "", "`$src`")
            }.distinct()
            val named = callers.take(3).joinToString(" · ") + if (callers.size > 3) " (+${callers.size - 3} more)" else ""
            // the matcher's verdict depends only on the method and the URL, so the group's first call speaks for all
            val matches = asList(calls[0]["matches"])
            val loose = asList(calls[0]["looseMatches"])
            val target = JavaParser.callTarget(url)
            if (matches.isEmpty() && loose.isEmpty() && target != JavaParser.CallTarget.PROJECT) {
                val line = "- $call — ${callers.size} caller${if (callers.size == 1) "" else "s"}: $named"
                (if (target == JavaParser.CallTarget.FLOWABLE_API) flowable else elsewhere).add(line)
                continue
            }
            own.add("- $call _(from $named)_")
            for (m in matches) own.add("    - ✅ served by ${pyStr(m)}")
            // `≈` for a loose path match, the same "uncertain" marker the explorer uses: it shares a
            // path segment with the call but is not a confident hit, so it must not read as "served by".
            for (m in loose) own.add("    - ≈ possibly ${pyStr(m)}")
            if (matches.isEmpty() && target == JavaParser.CallTarget.PROJECT) {
                own.add("    - ⚠️ no endpoint in this project serves it")
            }
        }
        val out = ArrayList<String>()
        out.add("### REST endpoints CALLED by the app (→ matched code)")
        out.addAll(own)
        if (flowable.isNotEmpty()) {
            if (own.isNotEmpty()) out.add("")
            out.add("#### Flowable REST API used (served by the platform, not this project)")
            out.addAll(flowable)
        }
        if (elsewhere.isNotEmpty()) {
            if (own.isNotEmpty() || flowable.isNotEmpty()) out.add("")
            out.add("#### Other systems (another host, a base the project does not name, or a route)")
            out.addAll(elsewhere)
        }
        return out
    }

    /**
     * Model paths as the report prints them.
     *
     * Design exports sit deep in a module's resources (`module/src/main/resources/com/flowable/app/custom/
     * Name-bar.zip`), and every model inside one repeated that directory in its heading, its app row and its
     * references — 49 KB of a real 433 KB report. An archive whose file name no other archive shares is
     * written by that name (`Name-bar.zip!entry`), and [legend] says once where each one lives. `--slice`
     * renders one model on its own, with no legend to point at, and passes [NONE].
     */
    internal class FileRefs(private val short: Map<String, String> = emptyMap()) {

        /** [f] as printed — an archive path by its archive's file name when the legend names it. */
        fun of(f: Any?): String {
            val s = Fmt.scalar(f) ?: return ""
            val bang = s.indexOf('!')
            if (bang < 0) return s
            return short[s.substring(0, bang)]?.let { it + s.substring(bang) } ?: s
        }

        /** ` — \`path\`` after a heading or row, or nothing when the model has no file. */
        fun tail(f: Any?): String = of(f).ifEmpty { null }?.let { " — `$it`" } ?: ""

        /** The one line that says where the shortened archives are, or null when none is shortened. */
        fun legend(): String? = if (short.isEmpty()) null else
            "_Archives, named below by their file name:_ " +
                short.entries.sortedBy { it.value }.joinToString(" · ") { "`${it.value}` = `${it.key}`" }

        companion object {
            val NONE = FileRefs()

            /** The model buckets whose `file` the report prints. */
            private val BUCKETS = listOf(
                "apps", "processes", "cases", "decisions", "forms", "dataObjects", "dictionaries", "others",
                "agents", "services", "channels", "events", "policies", "actions", "liquibase",
            )

            fun of(result: Map<String, Any?>): FileRefs {
                val archives = LinkedHashSet<String>()
                fun take(f: Any?) {
                    val s = f as? String ?: return
                    if ('!' in s) archives.add(s.substringBefore('!'))
                }
                for (b in BUCKETS) for (m in Dyn.list(result[b])) take(Dyn.map(m)["file"])
                for (v in Dyn.map(result["modelIndex"]).values) take(v)
                val byName = archives.groupBy { it.substringAfterLast('/') }
                val short = archives.filter { '/' in it && byName.getValue(it.substringAfterLast('/')).size == 1 }
                    .associateWith { it.substringAfterLast('/') }
                return FileRefs(short)
            }
        }
    }

    /** `file:line` of a Java class, or the file alone when no line is known. */
    private fun fileLine(jc: Map<String, Any?>): String =
        listOfNotNull(Fmt.scalar(jc["file"]), Fmt.scalar(jc["line"])).joinToString(":")

    /**
     * Variables **with their provenance**: which scopes they live in, where they are set and where read.
     *
     * This section used to print `result.variables` — a flat list of names, and a narrow one: on the test
     * fixture it named 4 of the project's 17 variables, and included `notifierBean` (a bean, not a
     * variable). Meanwhile every `variable` node already carried `scopes`, `usages` with snippets,
     * `ioParams` (the in/out mappings that carry it between models) and `scriptSites` (the scripts that
     * touch it) — the facts you need before writing an expression or a delegate. None of it was rendered.
     *
     * `heuristic` variables are marked: those names come from parsing a script, not from a declaration,
     * so they may be a local, a typo or a misread.
     */
    @Suppress("UNCHECKED_CAST")
    private fun renderVariables(result: Map<String, Any?>, L: MutableList<String>) {
        val nodes = (asMap(result["graph"])["nodes"] as? List<Map<String, Any?>>)?.filter {
            it["type"] == "variable"
        } ?: emptyList()
        if (nodes.isEmpty()) {
            // Nothing in the graph (e.g. a bucket-only result): fall back to the flat name list.
            val names = asList(result["variables"])
            if (names.isNotEmpty()) L.add("**Variables:** " + Fmt.codeList(names) + "\n")
            return
        }
        // Past the cap, the variables shared by the most models — the contracts between them, which is what
        // a reader about to touch one needs. Taking the alphabetically first 60 showed names starting with
        // a–c on a 435-variable project and said nothing about why those. Listed by name either way.
        fun key(n: Map<String, Any?>) = n["key"]?.toString() ?: ""
        fun models(n: Map<String, Any?>) = asList(asMap(n["data"])["usedBy"]).size
        fun sites(n: Map<String, Any?>) = asMap(n["data"]).let { asList(it["writes"]).size + asList(it["reads"]).size }
        val capped = nodes.size > VARIABLES_LISTED
        val shown = (if (!capped) nodes else nodes.sortedWith(
            compareByDescending<Map<String, Any?>> { models(it) }.thenByDescending { sites(it) }.thenBy { key(it) }
        ).take(VARIABLES_LISTED)).sortedBy { key(it) }
        L.add("**Variables (${nodes.size})** — " +
            (if (capped) "the $VARIABLES_LISTED shared by the most models; " else "") +
            "where each one lives, is set and is read:\n")
        for (n in shown) {
            val d = asMap(n["data"])
            val own = key(n)
            // `writes`/`reads` say which element sets or reads the variable and how — the direction a reader
            // needs before changing it. An element named after the variable itself (a DMN input column) says
            // nothing, so the model stands in for it; a script-inferred site is marked `≈` and goes last.
            fun sitesOf(v: Any?): List<String> = asList(v).map { asMap(it) }
                .sortedBy { if (it["guess"] == true) 1 else 0 }
                .mapNotNull { s ->
                    val en = Fmt.scalar(s["elementName"])?.ifBlank { null }
                    val el = Fmt.scalar(s["element"])?.ifBlank { null }
                    val name = when {
                        en != null -> en.takeIf { it != own }
                        else -> el?.takeIf { it != own }
                    } ?: Fmt.scalar(s["model"])?.substringAfter(':')?.ifBlank { null } ?: return@mapNotNull null
                    (if (s["guess"] == true) "≈ " else "") + Fmt.code(name) +
                        (Fmt.scalar(s["via"])?.ifBlank { null }?.let { " ($it)" } ?: "")
                }.distinct()
            val setBy = sitesOf(d["writes"])
            val readBy = sitesOf(d["reads"])
            val sited = (asList(d["writes"]) + asList(d["reads"])).mapNotNull { Fmt.scalar(asMap(it)["model"]) }.toSet()
            val scopes = Fmt.list(d["scopes"])
            // `in on \`callSub\`: orderId→subOrderId`, or just the target when a mapping has no source
            // (a literal or expression feeding a bot input) — never `None→customerEmail`.
            val params = (d["ioParams"] as? List<Map<String, Any?>> ?: emptyList()).map {
                val src = Fmt.list(it["source"])
                val tgt = Fmt.list(it["target"])
                val mapping = when {
                    src.isNotEmpty() && tgt.isNotEmpty() && src != tgt -> ": $src→$tgt"
                    tgt.isNotEmpty() -> ": $tgt"
                    else -> ""
                }
                Fmt.join("${pyStr(it["dir"])} on", Fmt.codeList(it["element"])) + mapping
            }.distinct()
            // Only sites we can name — an action's bot script has no element of its own. A script already
            // named under set by / read by, with its direction, is not named a second time without one.
            val allScripts = (d["scriptSites"] as? List<Map<String, Any?>> ?: emptyList())
                .mapNotNull { s ->
                    val name = orAny(s["elementName"], s["element"], "")
                    if (truthy(name)) Fmt.code(pyStr(name)) else null
                }.distinct()
            val directed = (setBy.take(3) + readBy.take(3)).joinToString(" ")
            val scripts = allScripts.filterNot { directed.contains(it) }
            // "(in|out parameter on X) a → b" / "(script ≈ read · Stamp order)" / "(form field)" — the
            // harvesters already phrase where a variable came from, so keep their words; but drop the
            // ones a structured field below already states — a parenthesised note for a model that set by /
            // read by covers, a parameter `passed as` lists, a script — or every variable says it twice.
            // A model left with nothing to quote is still named: the elements below do not say which
            // model they are in.
            val where = (d["usages"] as? List<Map<String, Any?>> ?: emptyList())
                .flatMap { u ->
                    val modelId = u["model"]?.toString() ?: ""
                    val model = modelId.substringAfter(':')
                    val kept = asList(u["snippets"]).map { pyStr(it) }
                        .filterNot { it.startsWith("(") && modelId in sited }
                        .filterNot { params.isNotEmpty() && it.contains("parameter on") }
                        .filterNot { allScripts.isNotEmpty() && it.contains("(script") }
                    // an expression is code: outside a span, `"<strong>" + cc` in a form expression was HTML
                    if (kept.isEmpty() && modelId in sited) listOf(model)
                    else kept.map { "$model " + if (it.startsWith("(")) it else Fmt.code(it) }
                }
            val head = Fmt.join(
                "- `${pyStr(n["key"])}`",
                if (scopes.isNotEmpty()) "[$scopes]" else "",
                if (d["heuristic"] == true) "⚠ _inferred from a script_" else "",
            )
            L.add(head)
            val detail = Fmt.fields(
                "used in" to Fmt.cap(where, 4),
                "set by" to Fmt.cap(setBy, 3),
                "read by" to Fmt.cap(readBy, 3),
                "passed as" to Fmt.cap(params, 3),
                "touched by scripts" to Fmt.cap(scripts, 3),
            )
            if (detail.isNotEmpty()) L.add("    - $detail")
        }
        if (nodes.size > VARIABLES_LISTED) {
            L.add("- … (+${nodes.size - VARIABLES_LISTED} more — every variable is a node in the graph)")
        }
        L.add("")
    }

    /**
     * Expressions grouped by the bean or function they call, with their problems marked.
     *
     * This used to be a `<details>` dump of every expression string in the project — 492 lines / 23 KB on
     * a real project, alphabetically sorted, with no indication that some of them do not parse. Collapsing
     * the block hides it from a human but costs an LLM the same tokens either way. Grouping by callee
     * answers the question the list was there for ("what does this bean get used for") and marking the
     * broken ones stops a reader copying an expression Atlas already knows is invalid.
     */
    @Suppress("UNCHECKED_CAST")
    private fun renderExpressions(result: Map<String, Any?>, L: MutableList<String>, graphRef: String) {
        val nodes = (asMap(result["graph"])["nodes"] as? List<Map<String, Any?>>)?.filter {
            it["type"] == "expression" || it["type"] == "binding"
        } ?: emptyList()
        if (nodes.isEmpty()) {
            val expressions = asList(result["expressions"])
            if (expressions.isNotEmpty()) L.add("**Expressions:** " + Fmt.cap(expressions.map {
                "`${pyStr(it)}`"
            }, 30) + "\n")
            return
        }
        // The leading `${`/`{{` and the first identifier are what group an expression: `${myBean.x()}`
        // and `${myBean.y()}` belong together under `myBean`.
        val groups = LinkedHashMap<String, MutableList<Map<String, Any?>>>()
        for (n in nodes) {
            val text = n["key"]?.toString() ?: continue
            val inner = text.removePrefix("\${").removePrefix("#{").removePrefix("{{").trimStart()
            val head = Regex("^[A-Za-z_$][A-Za-z0-9_$]*(?::[A-Za-z0-9_$]+)?").find(inner)?.value
            groups.getOrPut(head?.ifEmpty { null } ?: "(other)") { ArrayList() }.add(n)
        }
        L.add("**Expressions (${nodes.size})** — grouped by what they call:\n")
        val ordered = groups.entries.sortedWith(compareByDescending<Map.Entry<String, MutableList<Map<String, Any?>>>> {
            it.value.size
        }.thenBy { it.key })
        for ((head, exprs) in ordered.take(EXPRESSION_GROUPS)) {
            val broken = exprs.count { e ->
                (asMap(e["data"])["problems"] as? List<Map<String, Any?>>)?.any { it["severity"] == "error" } == true
            }
            val suspect = exprs.count { e ->
                val p = asMap(e["data"])["problems"] as? List<Map<String, Any?>> ?: emptyList()
                p.isNotEmpty() && p.none { it["severity"] == "error" }
            }
            val flags = Fmt.fields("invalid" to (if (broken > 0) "$broken ⚠" else ""),
                "suspect" to (if (suspect > 0) "$suspect" else ""))
            L.add("- `$head` (${exprs.size})" + (if (flags.isEmpty()) "" else " — $flags"))
            for (e in exprs.take(EXPRESSIONS_PER_GROUP)) {
                val problems = asMap(e["data"])["problems"] as? List<Map<String, Any?>> ?: emptyList()
                val mark = when {
                    problems.any { it["severity"] == "error" } -> " ⚠ "
                    problems.isNotEmpty() -> " ? "
                    else -> " "
                }
                val users = Fmt.cap(asList(asMap(e["data"])["usedBy"]).map {
                    "`${pyStr(it).substringAfter(':')}`"
                }, 3)
                L.add("    -$mark${Fmt.code(pyStr(e["key"]))}" + (if (users.isEmpty()) "" else " — in $users"))
            }
            if (exprs.size > EXPRESSIONS_PER_GROUP) {
                L.add("    - … (+${exprs.size - EXPRESSIONS_PER_GROUP} more)")
            }
        }
        if (groups.size > EXPRESSION_GROUPS) {
            L.add("- … (+${groups.size - EXPRESSION_GROUPS} more callees — every expression is a node in " +
                "$graphRef)")
        }
        L.add("")
    }

    /** One listener as a report line — what runs, on which event — or null when it names no code at all.
     *  A script-only listener counts: it has no class or expression, and skipping it hid code that runs. */
    private fun listenerLine(ls: Map<String, Any?>): String? {
        val impl = orAny(ls["class"], ls["delegateExpression"], ls["expression"],
            if (truthy(ls["script"])) "(script)" else null)
        if (!truthy(impl)) return null
        return "🎧 ${DesignTerms.label("el", ls["kind"])} [${pyStr(ls["event"])}] → ${pyStr(impl)}"
    }

    /**
     * The plan-model tree, with each plan item's **entry/exit criteria resolved to their sentry's
     * condition**.
     *
     * A CMMN case has no sequence flows: what makes a plan item start or stop is its criteria, and the
     * condition behind one lives in a separate `sentries` list keyed by `sentryRef`. Listing the two
     * apart (plan items here, sentries there) left the reader to join them by id — so the report showed
     * a case's structure while withholding what actually drives it. [tree] holds that index.
     *
     * A process or case task also carries its in/out mappings, as a call activity's line does: what the
     * case hands to the model it starts and what it takes back is the other half of "what does this plan
     * item do", and a reader had to fetch `ioParameters` from the graph for it.
     */
    private fun renderStage(
        node: Map<String, Any?>,
        L: MutableList<String>,
        depth: Int,
        tree: CaseTree,
        titleSuffix: String = "",
    ) {
        val ind = "    ".repeat(depth)
        L.add("$ind- 📁 **${DesignTerms.label("el", node["type"])}** ${tree.own(node)}$titleSuffix")
        fun criteriaSuffix(ch: Map<String, Any?>): String = criteriaText(criteriaOf(node, ch), tree)
        for (chAny in asList(node["children"])) {
            val ch = asMap(chAny)
            val rules = asMap(ch["rules"]).entries.mapNotNull { ruleText(it.key, it.value) }
                .joinToString("") { " · $it" }
            if (ch.containsKey("children")) {
                renderStage(ch, L, depth + 1, tree, rules + criteriaSuffix(ch))
            } else {
                var extra = ""
                // the code a Java task runs and where its result goes, as a process's service task line says
                for (k in listOf(
                    "assignee", "formKey", "processRef", "caseRef", "decisionRef",
                    "serviceModelKey", "agentModelKey", "dataObjectKey",
                    "class", "delegateExpression", "expression", "resultVariable",
                )) {
                    if (truthy(ch[k])) extra += " $k=`${pyStr(ch[k])}`"
                }
                L.add("$ind    - ${DesignTerms.label("el", ch["type"])} " +
                    "${tree.own(ch)}$extra${ioSuffix(tree.case, ch["id"])}$rules${criteriaSuffix(ch)}")
            }
        }
    }

    /**
     * The criteria of [stage] that sit on its plan item [ch], in the model's order. They are stored on
     * the stage, keyed by the definition the plan item refers to; two plan items of one definition each
     * have their own, and the plan item id tells them apart where the model has one.
     */
    internal fun criteriaOf(stage: Map<String, Any?>, ch: Map<String, Any?>): List<Map<String, Any?>> {
        val id = ch["id"]?.toString() ?: return emptyList()
        val own = ch["planItemId"]?.toString()
        return asList(stage["criteria"]).map { asMap(it) }.filter { c ->
            val of = c["planItemId"]?.toString()
            c["planItemDef"]?.toString() == id && (own == null || of == null || of == own)
        }
    }

    /**
     * The criteria of one plan item, each after its ` · `. Several of one kind are alternatives — the
     * engine takes the first one that is satisfied — and every one after the first says so: `· entry on
     * complete "A" · or entry if ${late}`. Side by side without the word, a reader could not tell whether
     * all of them or any of them opens the gate, and one who greps a single line sees no legend.
     */
    private fun criteriaText(crits: List<Map<String, Any?>>, tree: CaseTree): String {
        val gates = HashSet<Boolean>()
        return crits.joinToString("") {
            " · " + (if (gates.add(it["type"] == "exitCriterion")) "" else "or ") + criterionText(it, tree)
        }
    }

    /**
     * A criterion as the gate and what opens it: `entry on complete "Review" if ${ready}` (the condition
     * in a code span). A sentry can wait for an event and a condition at once, and printing only the
     * condition hid the event — readable only in the sentry list below the tree. [CaseTree.shown] collects
     * the sentries spelled out this way, so that list can leave them out.
     *
     * A sentry with neither event nor condition is satisfied the moment the engine evaluates it, so the
     * item starts (or is exited) as soon as its stage is active. It printed as a bare `entry`, which reads
     * as a criterion whose condition got lost. `exitEventType` and `exitType` follow where the model sets
     * them: an exit that *completes* its stage fires every sentry waiting for that stage to complete, a
     * plain one fires none of them.
     */
    private fun criterionText(c: Map<String, Any?>, tree: CaseTree): String =
        Fmt.join(if (c["type"] == "exitCriterion") "exit" else "entry", criterionWhat(c, tree))

    /**
     * What opens a criterion's gate, without the gate's name — blank for a criterion whose sentry the
     * model does not hold. Apart from [criterionText] so a storyline, which says entry and exit in its
     * own layout, words the sentry exactly as the plan tree does.
     */
    internal fun criterionWhat(c: Map<String, Any?>, tree: CaseTree): String {
        val ref = c["sentryRef"]?.toString()
        val sen = ref?.let { tree.sentries[it] } ?: return ""
        tree.shown.add(ref)
        val how = listOf("exitEventType", "exitType")
            .mapNotNull { k -> Fmt.scalar(c[k])?.ifBlank { null }?.let { "$k=$it" } }
        return Fmt.join(
            sentryText(sen, tree).ifEmpty { "at once (its sentry has no event and no condition)" },
            if (how.isEmpty()) "" else "(${how.joinToString(", ")})",
        )
    }

    /**
     * `on complete "Review" and occur "Skip" if <condition>` — what a sentry waits for; blank for an empty
     * sentry. Each on-part is the transition it waits for, where the model names one, and the plan item
     * by name (see [CaseTree.ref]). All of them have to happen, hence the *and*: a comma left that open.
     *
     * `(triggerMode=onEvent)` is said only where it changes something, which takes two things that have
     * to meet — an on-part and a condition, or two on-parts: in that trigger mode a satisfied part is not
     * remembered, so a condition that turns true after the event no longer opens the gate. Spelled as the
     * attribute it is: a bare `(onEvent)` was read as part of the event before it.
     */
    private fun sentryText(sen: Map<String, Any?>, tree: CaseTree): String {
        val events = asList(sen["events"]).map { asMap(it) }
            .associate { Fmt.scalar(it["source"]) to Fmt.scalar(it["event"]) }
        val parts = asList(sen["onParts"]).mapNotNull { Fmt.scalar(it)?.ifBlank { null } }
        val on = parts.joinToString(" and ") { Fmt.join(events[it].orEmpty(), tree.ref(it)) }
        val cond = Fmt.scalar(sen["condition"])?.ifBlank { null }
        val onEvent = Fmt.scalar(sen["triggerMode"]).equals("onEvent", ignoreCase = true) &&
            (parts.size >= 2 || (parts.isNotEmpty() && cond != null))
        return Fmt.join(
            if (on.isEmpty()) "" else "on $on", cond?.let { "if ${Fmt.code(it)}" } ?: "",
            if (onEvent) "(triggerMode=onEvent)" else "",
        )
    }

    /**
     * One case's plan items by the id a sentry names them by, and what else its tree is rendered from.
     *
     * A sentry's on-part holds a plan item id (`planItemprocessTask14`), and the tree lists plan items by
     * name. Printed as stored, a criterion read `entry on planItemprocessTask14`: an id no line of the tree
     * carries, so a reader could not tell which item has to complete — and had to open the graph to learn
     * it. [ref] says the item by the name its own line shows.
     */
    internal class CaseTree(val case: Map<String, Any?>, val sentries: Map<String, Map<String, Any?>>) {
        /**
         * The sentries a plan-tree line already spells out. Listing them again after the tree was 42% of a
         * real report's case section; only the ones no criterion reaches are left to list.
         */
        val shown = HashSet<String>()

        private val plan = asMap(case["planModel"])
        private val byRef = HashMap<String, Map<String, Any?>>()
        private val parentOf = java.util.IdentityHashMap<Map<String, Any?>, Map<String, Any?>>()
        private val nameCount = HashMap<String, Int>()

        /** The plan items some on-part names — the only ones whose line may need an id to be told apart. */
        private val named = java.util.Collections.newSetFromMap(java.util.IdentityHashMap<Map<String, Any?>, Boolean>())

        init {
            fun walk(node: Map<String, Any?>) {
                for (ch in asList(node["children"]).map { asMap(it) }) {
                    parentOf[ch] = node
                    // The plan item's id is what an on-part holds; the definition's stands in for a model
                    // that gives its plan items none, and never replaces one that was already found.
                    (ch["id"] as? String)?.let { byRef.putIfAbsent(it, ch) }
                    (ch["planItemId"] as? String)?.let { byRef[it] = ch }
                    nameOf(ch)?.let { nameCount.merge(it, 1, Int::plus) }
                    if (ch.containsKey("children")) walk(ch)
                }
            }
            walk(plan)
            for (sen in sentries.values) {
                for (part in asList(sen["onParts"])) (part as? String)?.let { byRef[it] }?.let { named.add(it) }
            }
        }

        private fun nameOf(rec: Map<String, Any?>): String? = (rec["name"] as? String)?.trim()?.ifEmpty { null }

        private fun idOf(rec: Map<String, Any?>): String = (rec["planItemId"] ?: rec["id"])?.toString() ?: "?"

        private fun hasTwin(rec: Map<String, Any?>): Boolean {
            val name = nameOf(rec) ?: return false
            val parent = parentOf[rec] ?: return false
            return asList(parent["children"]).any { it !== rec && nameOf(asMap(it)) == name }
        }

        /**
         * A plan item as a criterion names it: `"Review"`. Where the name repeats in the case it is
         * qualified by the stage it sits in (`"Audit" in "Intake"`), and by its id where a sibling carries
         * the same name — [own] then puts that id on the item's line. An item without a name is its id,
         * as on its own line, and an id no plan item has stays as the model wrote it.
         */
        fun ref(id: String): String {
            val rec = byRef[id] ?: return Fmt.code(id)
            val name = nameOf(rec) ?: return Fmt.code(rec["id"]?.toString() ?: id)
            val said = "\"$name\""
            if ((nameCount[name] ?: 0) < 2) return said
            val parent = parentOf[rec]
            return when {
                hasTwin(rec) -> "$said (${Fmt.code(idOf(rec))})"
                parent == null || parent === plan -> "$said on the case plan"
                else -> "$said in " + (nameOf(parent)?.let { "\"$it\"" } ?: Fmt.code(parent["id"]?.toString() ?: "?"))
            }
        }

        /** A plan item's name on its own line, with its id only where a criterion tells it from a sibling by it. */
        fun own(rec: Map<String, Any?>): String {
            val name = pyStr(orAny(rec["name"], rec["id"], ""))
            return if (rec in named && hasTwin(rec)) "$name (${Fmt.code(idOf(rec))})" else name
        }
    }

    /**
     * The mappings of one element as they follow its line: the `<flowable:in>`/`<flowable:out>` of a call
     * (` in(orderId→subOrderId) out(subTotal→total)`) and what an Init-Variables task assigns
     * (` set(approved=false)`). They live in the model's flat `ioParameters` rollup, stamped with the
     * element that declares them (see Ctx.addParams).
     *
     * What a source is decides how it prints. A variable is bare. A literal `sourceExpression` is quoted
     * (`in("express"→priority)`), because bare it read as a variable of that name being copied. An
     * expression is a code span, as every other expression in the report. A mapping without a source or
     * a target keeps its arrow (`in(→reviewTask)`), where it printed `None→reviewTask`.
     *
     * An assignment says its value by the type the model gives it: a string quoted, a variable or an
     * expression — both are EL the task evaluates — in a code span, a boolean or a number as it is, and
     * the type alone where the model sets no value (`set(draft: jsonObject)`). The line used to end at the
     * task's delegate expression, which every such task of a project shares.
     */
    private fun ioSuffix(model: Map<String, Any?>, elementId: Any?): String =
        asList(model["ioParameters"]).map { asMap(it) }
            .filter { it["element"] == elementId && it["kind"] in listOf("in", "out", "variableMapping") }
            .joinToString("") { io ->
                val src = Fmt.scalar(io["source"])?.ifBlank { null }
                val tgt = Fmt.scalar(io["target"]).orEmpty()
                if (io["kind"] == "variableMapping") {
                    // a mapping may write into a container: the `name` field of `contact`
                    val into = Fmt.scalar(io["container"])?.ifBlank { null }?.takeIf { !tgt.startsWith("$it.") }
                    val type = Fmt.scalar(io["type"])?.ifBlank { null }
                    val value = when {
                        src == null -> type?.let { ": $it" }.orEmpty()
                        io["expression"] == true || type == "variable" -> "=" + Fmt.code(src)
                        type == "string" -> "=\"$src\""
                        else -> "=$src"
                    }
                    return@joinToString " set(${into?.let { "$it." }.orEmpty()}$tgt$value)"
                }
                val from = when {
                    src == null -> ""
                    io["expression"] != true -> src
                    src.contains("\${") || src.contains("#{") -> Fmt.code(src)
                    else -> "\"$src\""
                }
                " ${pyStr(io["dir"])}($from→$tgt)"
            }

    /**
     * A plan item's rule as the few words it means: `required`, `repeats while <condition>`, `manual
     * activation`. An unconditional rule is stored as `true`, and printed as `key=value` it read
     * `requiredRule=True`; a conditional one carried its raw, multi-line condition outside a code span.
     */
    private fun ruleText(key: String, v: Any?): String? {
        if (v == null || v == false) return null
        val always = v == true || (v is String && (v.isBlank() || v.trim().equals("true", ignoreCase = true)))
        val cond = if (always) null else Fmt.code(Fmt.scalar(v) ?: "")
        return when (key) {
            "requiredRule" -> if (cond == null) "required" else "required if $cond"
            "manualActivationRule" -> if (cond == null) "manual activation" else "manual activation if $cond"
            "repetitionRule" -> if (cond == null) "repeats" else "repeats while $cond"
            "completionNeutralRule" -> if (cond == null) "completion-neutral" else "completion-neutral if $cond"
            else -> if (always) key else "$key=${Fmt.scalar(v)}"
        }
    }

    // ---- Python str()/repr()/truthiness helpers -------------------------------------------------

    @Suppress("UNCHECKED_CAST")
    /**
     * Rank each element of a process by **execution order**: a topological sort over its sequence
     * flows, start events first, and parallel siblings in the order their flows are declared — so a
     * gateway's branches are listed in the same order the gateway's own `next:` line names them.
     *
     * A process is stored grouped by element type, so rendering it in storage order buries the start
     * event among the last lines and never says what follows what. Sorting by the flows instead means
     * every step appears after the steps that can reach it.
     *
     * Robustness matters more than elegance here — real exports contain loops, unreachable fragments and
     * flows pointing at elements that live in a sub-process. So: a cycle releases its earliest-reached
     * member (document order only for members the walk never reached) and carries on, and anything the
     * flows never mention keeps its document position rather than disappearing.
     */
    internal fun flowOrder(p: Map<String, Any?>, docIds: List<String>): Map<String, Int> {
        val flows = asList(p["flows"]).map { asMap(it) }.mapNotNull { f ->
            val from = f["from"]?.toString()?.ifEmpty { null }
            val to = f["to"]?.toString()?.ifEmpty { null }
            if (from == null || to == null) null else from to to
        }
        val docPos = HashMap<String, Int>()
        docIds.forEachIndexed { i, id -> docPos.putIfAbsent(id, i) }
        // Start events lead, whatever bucket order put them in.
        val starts = asList(p["events"]).map { asMap(it) }
            .filter { it["type"] == "startEvent" }
            .mapNotNull { it["id"]?.toString()?.ifEmpty { null } }
            .toSet()
        fun pos(id: String): Int =
            (docPos[id] ?: Int.MAX_VALUE / 2) - (if (id in starts) docIds.size + 1 else 0)
        if (flows.isEmpty()) return docIds.associateWith { pos(it) }

        // Containment first, so a host lists what hangs on it before the flows it hands control to.
        val contained = containmentEdges(p, flows)
        val edges = contained + flows
        // What hangs on a host, or opens a sub-process, follows that element at once: it takes the host's
        // place in the discovery order rather than queueing behind steps already found elsewhere.
        val flowTargets = flows.map { it.second }.toSet()
        val heldBy = contained.filter { (_, t) -> t !in flowTargets }.associate { (h, t) -> t to h }
        val nodes = LinkedHashSet<String>(docIds)
        for ((f, t) in edges) { nodes.add(f); nodes.add(t) }
        val outgoing = HashMap<String, MutableList<String>>()
        val indegree = HashMap<String, Int>()
        for (n in nodes) indegree[n] = 0
        for ((f, t) in edges) {
            outgoing.getOrPut(f) { ArrayList() }.add(t)
            indegree[t] = (indegree[t] ?: 0) + 1
        }
        // Discovery order: seeds by document position (start events lead), everything else in the order
        // the flows reach it. Ordering the frontier by discovery is what keeps a gateway's branches in
        // their declared order instead of in whatever order the buckets happened to store them.
        val discovered = HashMap<String, Int>()
        var seen = 0
        val ready = java.util.TreeSet<String>(compareBy({ discovered[it] ?: Int.MAX_VALUE }, { it }))
        // The real flows only: an element no flow mentions stays out of the walk even when something hangs
        // on it — and an event sub-process, which no flow enters, follows the walk with all it contains.
        val inFlow = HashSet<String>()
        for ((f, t) in flows) { inFlow.add(f); inFlow.add(t) }
        val seeds = nodes.filter { indegree[it] == 0 }.sortedWith(compareBy({ pos(it) }, { it }))
        for (seed in seeds.filter { it in inFlow }) {
            discovered[seed] = seen++
            ready.add(seed)
        }
        // Elements no flow mentions are also seeds, but they are not part of the walk — park them after
        // it, so a disconnected fragment cannot break the line a reader is following.
        val parked = nodes.size * 2
        var loose = parked
        for (seed in seeds.filter { it !in inFlow }) {
            discovered[seed] = loose++
            ready.add(seed)
        }
        val remaining = LinkedHashSet(nodes)
        val rank = HashMap<String, Int>()
        var n = 0
        while (remaining.isNotEmpty()) {
            // A cycle stalls the walk while nodes remain: release the earliest *discovered* one — the node
            // the walk is waiting on — and carry on. Discovery counters and document positions are different
            // scales: mixing them let an unreached task low in the file jump a loop's gateway. A parked seed
            // waiting in the frontier is no reason to stop: taken first, it opened an event sub-process in
            // the middle of a main flow that loops back.
            val head = ready.firstOrNull()?.takeIf { discovered[it]!! < parked }
            val next = head?.also { ready.remove(it) }
                ?: remaining.filter { (discovered[it] ?: parked) < parked }.minByOrNull { discovered[it]!! }
                ?: ready.pollFirst()
                ?: remaining.filter { it in discovered }.minByOrNull { discovered[it]!! }
                ?: remaining.minByOrNull { pos(it) }!!
            if (!remaining.remove(next)) continue
            rank[next] = n++
            for (t in outgoing[next] ?: emptyList()) {
                if (t !in discovered) discovered[t] = discovered[next]?.takeIf { heldBy[t] == next } ?: seen++
                indegree[t] = (indegree[t] ?: 1) - 1
                if ((indegree[t] ?: 0) <= 0 && t in remaining) ready.add(t)
            }
        }
        return rank
    }

    /**
     * The order [flowOrder] has to respect that no sequence flow draws.
     *
     * A boundary event has no incoming flow, so it was a seed of the walk: ranked by document position,
     * right after the start event and before the activity it hangs on — 13 of 14 such events on one real
     * project. A sub-process's own start event was a seed too, so its contents opened the process. Here a
     * boundary event follows its host, a sub-process's start events follow the sub-process, and the flow
     * out of an embedded sub-process waits for its end events, so its contents come before what follows it.
     * Only the order uses these: the `next:` lines and the reachability note still read the real flows.
     */
    private fun containmentEdges(p: Map<String, Any?>, flows: List<Pair<String, String>>): List<Pair<String, String>> {
        val subs = asList(p["subProcesses"]).map { asMap(it) }.mapNotNull { s -> s["id"]?.toString()?.let { it to s } }.toMap()
        val events = asList(p["events"]).map { asMap(it) }
        val out = ArrayList<Pair<String, String>>()
        val after = flows.groupBy({ it.first }, { it.second })
        for (e in events) {
            val id = e["id"]?.toString()?.ifEmpty { null } ?: continue
            val parent = e["parent"]?.toString()?.takeIf { it in subs }
            when (e["type"]) {
                "boundaryEvent" -> e["attachedTo"]?.toString()?.ifEmpty { null }?.let { out.add(it to id) }
                "startEvent" -> parent?.let { out.add(it to id) }
                "endEvent" -> if (parent != null && subs[parent]?.get("eventSubProcess") != true) {
                    for (t in after[parent].orEmpty()) out.add(id to t)
                }
            }
        }
        return out
    }

    /**
     * `elementId → ["approveTask [${total > 100}]", …]` from the sequence flows — what each step hands
     * control to, with the condition or flow name that selects it. This replaced a separate list of
     * conditional flows at the end of each process, which stated the same fact further from the element
     * it belongs to and said nothing about the unconditional ones.
     */
    private fun successorsByElement(p: Map<String, Any?>): Map<String, List<String>> {
        val out = LinkedHashMap<String, MutableList<String>>()
        for (fAny in asList(p["flows"])) {
            val f = asMap(fAny)
            val from = f["from"]?.toString()?.ifEmpty { null } ?: continue
            val to = f["to"]?.toString()?.ifEmpty { null } ?: continue
            val label = when {
                truthy(f["condition"]) -> " [${Fmt.code(pyStr(f["condition"]))}]"
                truthy(f["name"]) -> " (${pyStr(f["name"])})"
                else -> ""
            }
            out.getOrPut(from) { ArrayList() }.add("`$to`$label")
        }
        return out
    }

    // Delegate rather than re-cast: the unchecked cast belongs in Dyn, which is the one place auditing
    // it. Kept as local names because this file calls them dozens of times.
    private fun asMap(v: Any?): Map<String, Any?> = Dyn.map(v)

    private fun asList(v: Any?): List<Any?> = Dyn.list(v)

    /** Python truthiness. */
    private fun truthy(v: Any?): Boolean = when (v) {
        null -> false
        is Boolean -> v
        is Number -> v.toDouble() != 0.0
        is String -> v.isNotEmpty()
        is Collection<*> -> v.isNotEmpty()
        is Map<*, *> -> v.isNotEmpty()
        else -> true
    }

    /** Python `a or b or …` — first truthy operand, else the last. */
    private fun orAny(vararg vals: Any?): Any? {
        for (v in vals) if (truthy(v)) return v
        return vals.last()
    }

    /** `v or ''` rendered through str(). */
    private fun orE(v: Any?): String = if (truthy(v)) pyStr(v) else ""

    /**
     * Whether a form component renders, can be used and is submitted, as the shortest true statement:
     * `*(hidden)*` when the model settles it, `visible when \`{{…}}\`` when it is a condition. A reader who
     * is told a form has a button and not told the button never appears has been told the wrong thing —
     * 252 of 338 buttons in one real project are `visible: false`.
     */
    private fun gates(settings: Map<String, Any?>): String {
        val out = ArrayList<String>()
        for ((field, settled, word) in GATES) {
            val v = settings[field] ?: continue
            if (v == settled) out.add("*($word)*")
            // the other literal is the default — always shown, always enabled — and says nothing
            else if (v is Boolean) continue
            // `ignore` reads backwards as a condition ("ignore when x" sounds like an instruction), so it
            // is phrased as what actually happens to the value.
            else out.add((if (field == "ignore") "value dropped when" else "$field when") +
                " `${oneLine(v, 60)}`")
        }
        return out.joinToString(" ")
    }

    /** `field`, the literal that settles it, and what that state is called. */
    private val GATES = listOf(
        Triple("visible", false, "hidden"),
        Triple("enabled", false, "disabled"),
        Triple("ignore", true, "not submitted"),
    )

    /**
     * A code value on one Markdown line: whitespace collapsed, backticks stripped (they would end the
     * inline code span), long bodies elided. An expression button's expression is usually a one-liner but
     * nothing stops it being a formatted block.
     */
    private fun oneLine(v: Any?, max: Int = 120): String {
        // A JSON value stays JSON: a script button that sets a variable to `true` read "= `True`", and one
        // that loads a default object, or a condition stored as an object, read as a Python dict.
        val raw = when (v) {
            is Boolean, is Map<*, *>, is Collection<*> -> MiniJson.stringify(v)
            else -> pyStr(v)
        }
        val s = raw.replace('`', '\'').replace(Regex("\\s+"), " ").trim()
        return if (s.length <= max) s else s.take(max - 1) + "…"
    }

    /** Format a number the way a Python f-string does (integral values drop the trailing `.0`). */
    private fun numStr(n: Number): String = when (n) {
        is Double -> if (n.isFinite() && n == Math.floor(n)) n.toLong().toString() else n.toString()
        is Float -> { val d = n.toDouble(); if (d.isFinite() && d == Math.floor(d)) d.toLong().toString() else n.toString() }
        else -> n.toString()
    }

    /**
     * Python `str(v)` — for a value that is always there. `null` prints `None` and `true` prints `True`:
     * a field a model may leave out, or a rule stored as `true`, goes through [Fmt.scalar] / [Fmt.fields]
     * instead. Those two shapes leaked into every real project's report until `MarkdownHygieneTest` ran
     * over the public sample as well as the fixture.
     */
    private fun pyStr(v: Any?): String = when (v) {
        null -> "None"
        is Boolean -> if (v) "True" else "False"
        is Number -> numStr(v)
        is String -> v
        is List<*> -> pyRepr(v)
        is Map<*, *> -> pyRepr(v)
        else -> v.toString()
    }

    /** Python `repr(v)`. */
    private fun pyRepr(v: Any?): String = when (v) {
        null -> "None"
        is Boolean -> if (v) "True" else "False"
        is Number -> numStr(v)
        is String -> reprStr(v)
        is List<*> -> v.joinToString(", ", "[", "]") { pyRepr(it) }
        is Map<*, *> -> v.entries.joinToString(", ", "{", "}") { "${pyRepr(it.key)}: ${pyRepr(it.value)}" }
        else -> v.toString()
    }

    /** Python `repr(str)` — single quotes unless the string has a `'` but no `"`. */
    private fun reprStr(str: String): String {
        val quote = if (str.contains('\'') && !str.contains('"')) '"' else '\''
        val sb = StringBuilder()
        sb.append(quote)
        for (c in str) {
            when (c) {
                '\\' -> sb.append("\\\\")
                '\n' -> sb.append("\\n")
                '\r' -> sb.append("\\r")
                '\t' -> sb.append("\\t")
                quote -> sb.append('\\').append(quote)
                else -> sb.append(c)
            }
        }
        sb.append(quote)
        return sb.toString()
    }
