// Builds the `updatePlugins.xml` that turns a plain download page into a custom plugin repository.
//
// Why this exists: Atlas is not on the JetBrains Marketplace, so nothing tells a colleague that a new
// version came out — the ZIP they installed months ago keeps running, silently old. A custom plugin
// repository is the supported way to fix that without a Marketplace listing: point IntelliJ at one URL
// (Settings → Plugins → ⚙ → Manage Plugin Repositories…) and Atlas joins the normal update flow, with
// the usual "update available" badge and one-click install.
//
// Everything except the download URL is READ OUT OF THE BUILT DESCRIPTOR rather than written here.
// A hand-maintained since-build/until-build in this file would be a second source of truth for the
// compatibility range, and the first thing it would do is drift from the plugin it describes — which
// is the one defect that makes an update channel actively harmful: the IDE would offer an update it
// cannot install, or hide one it could.
//
// Usage:
//   node scripts/make-update-plugins.mjs <patched-plugin.xml> <download-url> <output.xml>
//
// The release workflow passes the descriptor that `patchPluginXml` produced, so the version here is
// always the version that was actually built.

import fs from 'node:fs';

const [descriptorPath, downloadUrl, outPath] = process.argv.slice(2);
if (!descriptorPath || !downloadUrl || !outPath) {
  console.error('usage: make-update-plugins.mjs <patched-plugin.xml> <download-url> <output.xml>');
  process.exit(2);
}

const xml = fs.readFileSync(descriptorPath, 'utf8');

// Deliberately small regexes rather than an XML parser: the descriptor is generated by Gradle, these
// four fields sit at its top level, and adding a dependency to read them would be the larger risk.
// Each one fails loudly below if the shape ever changes, which is the behaviour that matters.
const pick = (re, what) => {
  const m = xml.match(re);
  if (!m) throw new Error(`could not read ${what} from ${descriptorPath} — has the descriptor shape changed?`);
  return m[1];
};

const id = pick(/<id>([^<]+)<\/id>/, '<id>');
const name = pick(/<name>([^<]+)<\/name>/, '<name>');
const version = pick(/<version>([^<]+)<\/version>/, '<version>');
const sinceBuild = pick(/<idea-version[^>]*\ssince-build="([^"]+)"/, 'since-build');
const untilBuild = pick(/<idea-version[^>]*\suntil-build="([^"]+)"/, 'until-build');

// A literal <version> in the source descriptor was removed on purpose (patchPluginXml injects it), so
// reading one back that still says 0.10.4 would mean we were handed the SOURCE file, not the patched
// one — and every colleague would be offered a downgrade.
if (!/^\d+\.\d+\.\d+/.test(version)) {
  throw new Error(`refusing to publish a repository for version "${version}" — expected a patched descriptor`);
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const out = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make-update-plugins.mjs — do not edit.
     Add this file's URL under Settings → Plugins → ⚙ → Manage Plugin Repositories… -->
<plugins>
  <plugin id="${esc(id)}" url="${esc(downloadUrl)}" version="${esc(version)}">
    <name>${esc(name)}</name>
    <idea-version since-build="${esc(sinceBuild)}" until-build="${esc(untilBuild)}"/>
  </plugin>
</plugins>
`;

fs.writeFileSync(outPath, out);
console.log(`${outPath}: ${id} ${version} (${sinceBuild}–${untilBuild})\n  -> ${downloadUrl}`);
